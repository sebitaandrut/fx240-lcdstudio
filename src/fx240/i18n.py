def translate(text,language='en'):
    return SPANISH.get(text,text) if language=='es' else text


def runtime_text(text,language='en'):
    if language!='es':return text
    if text in SPANISH:return SPANISH[text]
    if text.startswith('Sample #'):return text.replace('Sample #','Muestra #',1)
    for source in ('USB not opened','reports/frame','ms pipeline','frames'):
        text=text.replace(source,SPANISH[source])
    return text
